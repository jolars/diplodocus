#[path = "src/execution/identity/build_metadata.rs"]
mod build_metadata;

use clap::CommandFactory;

// The build script reads the command metadata without dispatching commands.
#[allow(dead_code)]
#[path = "src/cli.rs"]
mod cli;

fn main() {
    for path in [
        "Cargo.lock",
        "Cargo.toml",
        "build.rs",
        "src/execution/identity/build_metadata.rs",
        "src/cli.rs",
        "docs/cli-intro.md",
    ] {
        println!("cargo:rerun-if-changed={path}");
    }
    let lock = std::fs::read_to_string("Cargo.lock").expect("read locked component graph");
    let version = std::env::var("CARGO_PKG_VERSION").expect("Cargo package version");
    for (variable, name) in [
        ("DIPLODOCUS_PANACHE_VERSION", "panache-parser"),
        ("DIPLODOCUS_RUFF_VERSION", "ruff_python_parser"),
        ("DIPLODOCUS_FATOU_VERSION", "fatou-parser"),
    ] {
        let selected = build_metadata::selected_version(&lock, &version, name)
            .expect("unambiguous locked parser version");
        println!("cargo:rustc-env={variable}={selected}");
    }
    let components = build_metadata::components(&lock, &version)
        .expect("unambiguous locked execution components");
    let mut generated = String::from("pub const COMPONENTS: &[(&str, &str, &str)] = &[\n");
    for (role, name, version) in components {
        generated.push_str(&format!("({role:?}, {name:?}, {version:?}),\n"));
    }
    generated.push_str("];\n");
    for (constant, variable) in [
        ("TARGET", "TARGET"),
        ("OS", "CARGO_CFG_TARGET_OS"),
        ("ARCH", "CARGO_CFG_TARGET_ARCH"),
    ] {
        let value = std::env::var(variable).expect("Cargo target metadata");
        assert!(!value.is_empty(), "empty Cargo target metadata");
        generated.push_str(&format!("pub const {constant}: &str = {value:?};\n"));
    }
    let destination =
        std::path::PathBuf::from(std::env::var_os("OUT_DIR").expect("Cargo output directory"));
    std::fs::write(destination.join("execution_build.rs"), generated)
        .expect("write execution build metadata");

    generate_cli_markdown().expect("write CLI reference");
}

fn generate_cli_markdown() -> std::io::Result<()> {
    let root = std::path::PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("Cargo manifest directory"),
    );
    let reference = root.join("docs/reference");
    // Published crates can omit the documentation sources.
    if !reference.is_dir() {
        return Ok(());
    }

    let command = cli::Cli::command().long_about(include_str!("docs/cli-intro.md").trim());
    let options = clapdown::Options::new()
        .title("Commands")
        .footer(false)
        .table_of_contents(false);
    let markdown = clapdown::render(&command, &options);
    let mut lines = markdown.lines().peekable();
    let mut generated = String::from(
        "[//]: # (Generated by clapdown from src/cli.rs and docs/cli-intro.md. Do not edit.)\n\n",
    );
    // GFM lacks definition lists, so retain their content as list items.
    while let Some(line) = lines.next() {
        if line.starts_with('`')
            && let Some(definition) = lines.peek().and_then(|line| line.strip_prefix(":   "))
        {
            generated.push_str(&format!("- {line}\n\n    {definition}\n"));
            lines.next();
        } else {
            generated.push_str(line);
            generated.push('\n');
        }
    }

    let path = reference.join("cli.md");
    // Avoid triggering documentation watchers when the reference is unchanged.
    if std::fs::read_to_string(&path).ok().as_deref() != Some(&generated) {
        std::fs::write(path, generated)?;
    }
    Ok(())
}
